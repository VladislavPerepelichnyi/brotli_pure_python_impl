"""Hash table on the 4-byte prefixes of static dictionary words
(port of c/enc/dictionary_hash.h / dictionary_hash.c with the embedded tables
of dictionary_hash_inc.h; BROTLI_STATIC_INIT == NONE in the reference build).

The tables are stored in dictionary_hash.bin (generated by
tools/gen_dictionary_hash.py from the C header).
"""

import os
from array import array

# Bucket is (Hash14 * 2 + length_lt_8); in other words we reserve 2 buckets
# for each hash - one for shorter words and one for longer words.
BROTLI_ENC_NUM_HASH_BUCKETS = 32768

_PATH = os.path.join(os.path.dirname(__file__), 'dictionary_hash.bin')

with open(_PATH, 'rb') as _f:
    _raw = _f.read()

assert len(_raw) == 3 * BROTLI_ENC_NUM_HASH_BUCKETS

_words = array('H')
_words.frombytes(_raw[:2 * BROTLI_ENC_NUM_HASH_BUCKETS])
if _words.itemsize != 2:  # pragma: no cover
    raise ImportError('unexpected array item size')
import sys as _sys
if _sys.byteorder != 'little':  # pragma: no cover
    _words.byteswap()

#: kStaticDictionaryHashWords (tuple of 32768 ints)
kStaticDictionaryHashWords = tuple(_words)
#: kStaticDictionaryHashLengths (bytes of length 32768)
kStaticDictionaryHashLengths = bytes(_raw[2 * BROTLI_ENC_NUM_HASH_BUCKETS:])

del _raw, _words, _f
