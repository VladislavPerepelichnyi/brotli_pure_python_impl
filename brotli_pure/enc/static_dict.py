"""Static dictionary match finder (port of c/enc/static_dict.c, static_dict.h
and the lookup tables of c/enc/static_dict_lut.h / static_dict_lut_inc.h).

Only the built-in RFC 7932 dictionary / transforms are supported (no shared
or contextual dictionaries), which is what the public ``compress`` API uses.

The lookup table data lives in ``static_dict_lut.bin`` (generated by
``tools/gen_static_dict_lut.py`` from ``static_dict_lut_inc.h``).
"""

import os
import sys
from array import array

from ..common.dictionary import DATA as _DICT_DATA
from ..common.dictionary import OFFSETS_BY_LENGTH as _OFFSETS
from ..common.dictionary import SIZE_BITS_BY_LENGTH as _SIZE_BITS

# BROTLI_MAX_STATIC_DICTIONARY_MATCH_LEN
BROTLI_MAX_STATIC_DICTIONARY_MATCH_LEN = 37
# kInvalidMatch
K_INVALID_MATCH = 0xFFFFFFF

BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS = 32768
BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS = 31705

BROTLI_TRANSFORM_UPPERCASE_FIRST = 10

# kCutoffTransforms / kCutoffTransformsCount (c/enc/hash.h)
K_CUTOFF_TRANSFORMS_COUNT = 10
K_CUTOFF_TRANSFORMS = 0x071B520ADA2D3200

K_HASH_MUL32 = 0x1E35A7BD


def _load_lut():
    path = os.path.join(os.path.dirname(__file__), "static_dict_lut.bin")
    with open(path, "rb") as f:
        raw = f.read()
    nb = BROTLI_ENC_STATIC_DICT_LUT_NUM_BUCKETS
    ni = BROTLI_ENC_STATIC_DICT_LUT_NUM_ITEMS
    assert len(raw) == 2 * nb + 4 * ni
    buckets = array("H")
    buckets.frombytes(raw[:2 * nb])
    words = raw[2 * nb:]
    lens = bytes(words[0::4])
    transforms = bytes(words[1::4])
    pairs = array("H")
    pairs.frombytes(words)
    if sys.byteorder != "little":
        buckets.byteswap()
        pairs.byteswap()
    idx = pairs[1::2]
    return list(buckets), lens, transforms, list(idx)


# kStaticDictionaryBuckets, kStaticDictionaryWords (split in 3 columns).
K_STATIC_DICTIONARY_BUCKETS, DICT_WORD_LEN, DICT_WORD_TRANSFORM, \
    DICT_WORD_IDX = _load_lut()

# Precomputed (1 << size_bits_by_length[l]) for l in 0..31.
_N_BY_LEN = tuple(1 << b for b in _SIZE_BITS)

# Precomputed omit-last transform ids:
# (cut << 2) + ((cutoffTransforms >> (cut * 6)) & 0x3F), cut = 0..9
_CUTOFF_TRANSFORM_ID = tuple(
    (cut << 2) + ((K_CUTOFF_TRANSFORMS >> (cut * 6)) & 0x3F)
    for cut in range(K_CUTOFF_TRANSFORMS_COUNT))


def hash15(data, p):
    """Hash15 (c/enc/hash_base.h)."""
    v = data[p] | (data[p + 1] << 8) | (data[p + 2] << 16) | (data[p + 3] << 24)
    return ((v * K_HASH_MUL32) & 0xFFFFFFFF) >> 17


def _dict_match_length(data, p, id_, l, maxlen):
    """DictMatchLength: FindMatchLengthWithLimit(&dict[offset], data, min(l, maxlen))."""
    offset = _OFFSETS[l] + l * id_
    limit = l if l < maxlen else maxlen
    d = _DICT_DATA
    if d[offset:offset + limit] == data[p:p + limit]:
        return limit
    n = 0
    while d[offset + n] == data[p + n]:
        n += 1
    return n


def _is_match(l, transform, id_, data, p, max_length):
    """IsMatch (c/enc/static_dict.c)."""
    if l > max_length:
        return False
    offset = _OFFSETS[l] + l * id_
    d = _DICT_DATA
    if transform == 0:
        # Match against base dictionary word.
        return d[offset:offset + l] == data[p:p + l]
    elif transform == 10:
        # Match against uppercase first transform.
        c = d[offset]
        return (97 <= c <= 122 and (c ^ 32) == data[p] and
                d[offset + 1:offset + l] == data[p + 1:p + l])
    else:
        # Match against uppercase all transform.
        for i in range(l):
            c = d[offset + i]
            if 97 <= c <= 122:
                if (c ^ 32) != data[p + i]:
                    return False
            else:
                if c != data[p + i]:
                    return False
        return True


def brotli_find_all_static_dictionary_matches(dictionary, data, p, min_length,
                                              max_length, matches):
    """BrotliFindAllStaticDictionaryMatches / BrotliFindAllStaticDictionaryMatchesFor.

    ``data[p:]`` is the input to match. ``matches`` is a list of at least
    BROTLI_MAX_STATIC_DICTIONARY_MATCH_LEN + 1 ints initialised to
    K_INVALID_MATCH; for each length l a match was found, matches[l] is set to
    the minimum (distance << 5) + len_code.  Returns True if any match was
    found.  ``dictionary`` is ignored (only the built-in dictionary exists;
    dictionary->parent is NULL, so the multi-dictionary branch is skipped).
    """
    has_found_match = False
    buckets = K_STATIC_DICTIONARY_BUCKETS
    w_len = DICT_WORD_LEN
    w_tr = DICT_WORD_TRANSFORM
    w_idx = DICT_WORD_IDX
    n_by_len = _N_BY_LEN

    def add(distance, ln, len_code):
        # AddMatch
        m = (distance << 5) + len_code
        if m < matches[ln]:
            matches[ln] = m

    offset = buckets[hash15(data, p)]
    end = not offset
    while not end:
        wl = w_len[offset]
        transform = w_tr[offset]
        id_ = w_idx[offset]
        offset += 1
        l = wl & 0x1F
        n = n_by_len[l]
        end = (wl & 0x80) != 0
        if transform == 0:
            matchlen = _dict_match_length(data, p, id_, l, max_length)
            # Transform "" + BROTLI_TRANSFORM_IDENTITY + ""
            if matchlen == l:
                add(id_, l, l)
                has_found_match = True
            # Transforms "" + BROTLI_TRANSFORM_OMIT_LAST_1 + "" and
            #            "" + BROTLI_TRANSFORM_OMIT_LAST_1 + "ing "
            if matchlen >= l - 1:
                add(id_ + 12 * n, l - 1, l)
                if (l + 2 < max_length and data[p + l - 1] == 0x69 and
                        data[p + l] == 0x6E and data[p + l + 1] == 0x67 and
                        data[p + l + 2] == 0x20):
                    add(id_ + 49 * n, l + 3, l)
                has_found_match = True
            # Transform "" + BROTLI_TRANSFORM_OMIT_LAST_# + "" (# = 2 .. 9)
            minlen = min_length
            if l > 9 and l - 9 > minlen:
                minlen = l - 9
            maxlen = matchlen if matchlen < l - 2 else l - 2
            ln = minlen
            while ln <= maxlen:
                cut = l - ln
                add(id_ + _CUTOFF_TRANSFORM_ID[cut] * n, ln, l)
                has_found_match = True
                ln += 1
            if matchlen < l or l + 6 >= max_length:
                continue
            s = p + l
            s0 = data[s]
            # Transforms "" + BROTLI_TRANSFORM_IDENTITY + <suffix>
            if s0 == 0x20:  # ' '
                add(id_ + n, l + 1, l)
                s1 = data[s + 1]
                if s1 == 0x61:  # 'a'
                    s2 = data[s + 2]
                    if s2 == 0x20:
                        add(id_ + 28 * n, l + 3, l)
                    elif s2 == 0x73:  # 's'
                        if data[s + 3] == 0x20:
                            add(id_ + 46 * n, l + 4, l)
                    elif s2 == 0x74:  # 't'
                        if data[s + 3] == 0x20:
                            add(id_ + 60 * n, l + 4, l)
                    elif s2 == 0x6E:  # 'n'
                        if data[s + 3] == 0x64 and data[s + 4] == 0x20:
                            add(id_ + 10 * n, l + 5, l)
                elif s1 == 0x62:  # 'b'
                    if data[s + 2] == 0x79 and data[s + 3] == 0x20:
                        add(id_ + 38 * n, l + 4, l)
                elif s1 == 0x69:  # 'i'
                    s2 = data[s + 2]
                    if s2 == 0x6E:
                        if data[s + 3] == 0x20:
                            add(id_ + 16 * n, l + 4, l)
                    elif s2 == 0x73:
                        if data[s + 3] == 0x20:
                            add(id_ + 47 * n, l + 4, l)
                elif s1 == 0x66:  # 'f'
                    s2 = data[s + 2]
                    if s2 == 0x6F:  # 'o'
                        if data[s + 3] == 0x72 and data[s + 4] == 0x20:
                            add(id_ + 25 * n, l + 5, l)
                    elif s2 == 0x72:  # 'r'
                        if (data[s + 3] == 0x6F and data[s + 4] == 0x6D and
                                data[s + 5] == 0x20):
                            add(id_ + 37 * n, l + 6, l)
                elif s1 == 0x6F:  # 'o'
                    s2 = data[s + 2]
                    if s2 == 0x66:  # 'f'
                        if data[s + 3] == 0x20:
                            add(id_ + 8 * n, l + 4, l)
                    elif s2 == 0x6E:  # 'n'
                        if data[s + 3] == 0x20:
                            add(id_ + 45 * n, l + 4, l)
                elif s1 == 0x6E:  # 'n'
                    if (data[s + 2] == 0x6F and data[s + 3] == 0x74 and
                            data[s + 4] == 0x20):
                        add(id_ + 80 * n, l + 5, l)
                elif s1 == 0x74:  # 't'
                    s2 = data[s + 2]
                    if s2 == 0x68:  # 'h'
                        s3 = data[s + 3]
                        if s3 == 0x65:  # 'e'
                            if data[s + 4] == 0x20:
                                add(id_ + 5 * n, l + 5, l)
                        elif s3 == 0x61:  # 'a'
                            if data[s + 4] == 0x74 and data[s + 5] == 0x20:
                                add(id_ + 29 * n, l + 6, l)
                    elif s2 == 0x6F:  # 'o'
                        if data[s + 3] == 0x20:
                            add(id_ + 17 * n, l + 4, l)
                elif s1 == 0x77:  # 'w'
                    if (data[s + 2] == 0x69 and data[s + 3] == 0x74 and
                            data[s + 4] == 0x68 and data[s + 5] == 0x20):
                        add(id_ + 35 * n, l + 6, l)
            elif s0 == 0x22:  # '"'
                add(id_ + 19 * n, l + 1, l)
                if data[s + 1] == 0x3E:  # '>'
                    add(id_ + 21 * n, l + 2, l)
            elif s0 == 0x2E:  # '.'
                add(id_ + 20 * n, l + 1, l)
                if data[s + 1] == 0x20:
                    add(id_ + 31 * n, l + 2, l)
                    if data[s + 2] == 0x54 and data[s + 3] == 0x68:  # 'T' 'h'
                        s4 = data[s + 4]
                        if s4 == 0x65:  # 'e'
                            if data[s + 5] == 0x20:
                                add(id_ + 43 * n, l + 6, l)
                        elif s4 == 0x69:  # 'i'
                            if data[s + 5] == 0x73 and data[s + 6] == 0x20:
                                add(id_ + 75 * n, l + 7, l)
            elif s0 == 0x2C:  # ','
                add(id_ + 76 * n, l + 1, l)
                if data[s + 1] == 0x20:
                    add(id_ + 14 * n, l + 2, l)
            elif s0 == 0x0A:  # '\n'
                add(id_ + 22 * n, l + 1, l)
                if data[s + 1] == 0x09:  # '\t'
                    add(id_ + 50 * n, l + 2, l)
            elif s0 == 0x5D:  # ']'
                add(id_ + 24 * n, l + 1, l)
            elif s0 == 0x27:  # '\''
                add(id_ + 36 * n, l + 1, l)
            elif s0 == 0x3A:  # ':'
                add(id_ + 51 * n, l + 1, l)
            elif s0 == 0x28:  # '('
                add(id_ + 57 * n, l + 1, l)
            elif s0 == 0x3D:  # '='
                s1 = data[s + 1]
                if s1 == 0x22:
                    add(id_ + 70 * n, l + 2, l)
                elif s1 == 0x27:
                    add(id_ + 86 * n, l + 2, l)
            elif s0 == 0x61:  # 'a'
                if data[s + 1] == 0x6C and data[s + 2] == 0x20:
                    add(id_ + 84 * n, l + 3, l)
            elif s0 == 0x65:  # 'e'
                s1 = data[s + 1]
                if s1 == 0x64:  # 'd'
                    if data[s + 2] == 0x20:
                        add(id_ + 53 * n, l + 3, l)
                elif s1 == 0x72:  # 'r'
                    if data[s + 2] == 0x20:
                        add(id_ + 82 * n, l + 3, l)
                elif s1 == 0x73:  # 's'
                    if data[s + 2] == 0x74 and data[s + 3] == 0x20:
                        add(id_ + 95 * n, l + 4, l)
            elif s0 == 0x66:  # 'f'
                if (data[s + 1] == 0x75 and data[s + 2] == 0x6C and
                        data[s + 3] == 0x20):
                    add(id_ + 90 * n, l + 4, l)
            elif s0 == 0x69:  # 'i'
                s1 = data[s + 1]
                if s1 == 0x76:  # 'v'
                    if data[s + 2] == 0x65 and data[s + 3] == 0x20:
                        add(id_ + 92 * n, l + 4, l)
                elif s1 == 0x7A:  # 'z'
                    if data[s + 2] == 0x65 and data[s + 3] == 0x20:
                        add(id_ + 100 * n, l + 4, l)
            elif s0 == 0x6C:  # 'l'
                s1 = data[s + 1]
                if s1 == 0x65:  # 'e'
                    if (data[s + 2] == 0x73 and data[s + 3] == 0x73 and
                            data[s + 4] == 0x20):
                        add(id_ + 93 * n, l + 5, l)
                elif s1 == 0x79:  # 'y'
                    if data[s + 2] == 0x20:
                        add(id_ + 61 * n, l + 3, l)
            elif s0 == 0x6F:  # 'o'
                if (data[s + 1] == 0x75 and data[s + 2] == 0x73 and
                        data[s + 3] == 0x20):
                    add(id_ + 106 * n, l + 4, l)
        else:
            # Set is_all_caps=0 for BROTLI_TRANSFORM_UPPERCASE_FIRST and
            #     is_all_caps=1 otherwise (BROTLI_TRANSFORM_UPPERCASE_ALL)
            is_all_caps = transform != BROTLI_TRANSFORM_UPPERCASE_FIRST
            if not _is_match(l, transform, id_, data, p, max_length):
                continue
            # Transform "" + kUppercase{First,All} + ""
            add(id_ + (44 if is_all_caps else 9) * n, l, l)
            has_found_match = True
            if l + 1 >= max_length:
                continue
            # Transforms "" + kUppercase{First,All} + <suffix>
            s = p + l
            s0 = data[s]
            if s0 == 0x20:
                add(id_ + (68 if is_all_caps else 4) * n, l + 1, l)
            elif s0 == 0x22:  # '"'
                add(id_ + (87 if is_all_caps else 66) * n, l + 1, l)
                if data[s + 1] == 0x3E:
                    add(id_ + (97 if is_all_caps else 69) * n, l + 2, l)
            elif s0 == 0x2E:  # '.'
                add(id_ + (101 if is_all_caps else 79) * n, l + 1, l)
                if data[s + 1] == 0x20:
                    add(id_ + (114 if is_all_caps else 88) * n, l + 2, l)
            elif s0 == 0x2C:  # ','
                add(id_ + (112 if is_all_caps else 99) * n, l + 1, l)
                if data[s + 1] == 0x20:
                    add(id_ + (107 if is_all_caps else 58) * n, l + 2, l)
            elif s0 == 0x27:  # '\''
                add(id_ + (94 if is_all_caps else 74) * n, l + 1, l)
            elif s0 == 0x28:  # '('
                add(id_ + (113 if is_all_caps else 78) * n, l + 1, l)
            elif s0 == 0x3D:  # '='
                s1 = data[s + 1]
                if s1 == 0x22:
                    add(id_ + (105 if is_all_caps else 104) * n, l + 2, l)
                elif s1 == 0x27:
                    add(id_ + (116 if is_all_caps else 108) * n, l + 2, l)

    # Transforms with prefixes " " and "."
    d0 = data[p]
    if max_length >= 5 and (d0 == 0x20 or d0 == 0x2E):
        is_space = d0 == 0x20
        offset = buckets[hash15(data, p + 1)]
        end = not offset
        while not end:
            wl = w_len[offset]
            transform = w_tr[offset]
            id_ = w_idx[offset]
            offset += 1
            l = wl & 0x1F
            n = n_by_len[l]
            end = (wl & 0x80) != 0
            if transform == 0:
                if not _is_match(l, 0, id_, data, p + 1, max_length - 1):
                    continue
                # Transforms " " + BROTLI_TRANSFORM_IDENTITY + "" and
                #            "." + BROTLI_TRANSFORM_IDENTITY + ""
                add(id_ + (6 if is_space else 32) * n, l + 1, l)
                has_found_match = True
                if l + 2 >= max_length:
                    continue
                # Transforms " " + BROTLI_TRANSFORM_IDENTITY + <suffix> and
                #            "." + BROTLI_TRANSFORM_IDENTITY + <suffix>
                s = p + l + 1
                s0 = data[s]
                if s0 == 0x20:
                    add(id_ + (2 if is_space else 77) * n, l + 2, l)
                elif s0 == 0x28:  # '('
                    add(id_ + (89 if is_space else 67) * n, l + 2, l)
                elif is_space:
                    if s0 == 0x2C:  # ','
                        add(id_ + 103 * n, l + 2, l)
                        if data[s + 1] == 0x20:
                            add(id_ + 33 * n, l + 3, l)
                    elif s0 == 0x2E:  # '.'
                        add(id_ + 71 * n, l + 2, l)
                        if data[s + 1] == 0x20:
                            add(id_ + 52 * n, l + 3, l)
                    elif s0 == 0x3D:  # '='
                        s1 = data[s + 1]
                        if s1 == 0x22:
                            add(id_ + 81 * n, l + 3, l)
                        elif s1 == 0x27:
                            add(id_ + 98 * n, l + 3, l)
            elif is_space:
                # Set is_all_caps=0 for BROTLI_TRANSFORM_UPPERCASE_FIRST and
                #     is_all_caps=1 otherwise (BROTLI_TRANSFORM_UPPERCASE_ALL)
                is_all_caps = transform != BROTLI_TRANSFORM_UPPERCASE_FIRST
                if not _is_match(l, transform, id_, data, p + 1,
                                 max_length - 1):
                    continue
                # Transforms " " + kUppercase{First,All} + ""
                add(id_ + (85 if is_all_caps else 30) * n, l + 1, l)
                has_found_match = True
                if l + 2 >= max_length:
                    continue
                # Transforms " " + kUppercase{First,All} + <suffix>
                s = p + l + 1
                s0 = data[s]
                if s0 == 0x20:
                    add(id_ + (83 if is_all_caps else 15) * n, l + 2, l)
                elif s0 == 0x2C:  # ','
                    if not is_all_caps:
                        add(id_ + 109 * n, l + 2, l)
                    if data[s + 1] == 0x20:
                        add(id_ + (111 if is_all_caps else 65) * n, l + 3, l)
                elif s0 == 0x2E:  # '.'
                    add(id_ + (115 if is_all_caps else 96) * n, l + 2, l)
                    if data[s + 1] == 0x20:
                        add(id_ + (117 if is_all_caps else 91) * n, l + 3, l)
                elif s0 == 0x3D:  # '='
                    s1 = data[s + 1]
                    if s1 == 0x22:
                        add(id_ + (110 if is_all_caps else 118) * n, l + 3, l)
                    elif s1 == 0x27:
                        add(id_ + (119 if is_all_caps else 120) * n, l + 3, l)

    if max_length >= 6:
        # Transforms with prefixes "e ", "s ", ", " and "\xC2\xA0"
        d1 = data[p + 1]
        if ((d1 == 0x20 and (d0 == 0x65 or d0 == 0x73 or d0 == 0x2C)) or
                (d0 == 0xC2 and d1 == 0xA0)):
            offset = buckets[hash15(data, p + 2)]
            end = not offset
            while not end:
                wl = w_len[offset]
                transform = w_tr[offset]
                id_ = w_idx[offset]
                offset += 1
                l = wl & 0x1F
                n = n_by_len[l]
                end = (wl & 0x80) != 0
                if transform == 0 and _is_match(l, 0, id_, data, p + 2,
                                                max_length - 2):
                    if d0 == 0xC2:
                        add(id_ + 102 * n, l + 2, l)
                        has_found_match = True
                    elif l + 2 < max_length and data[p + l + 2] == 0x20:
                        t = 18 if d0 == 0x65 else (7 if d0 == 0x73 else 13)
                        add(id_ + t * n, l + 3, l)
                        has_found_match = True

    if max_length >= 9:
        # Transforms with prefixes " the " and ".com/"
        if ((d0 == 0x20 and data[p + 1] == 0x74 and data[p + 2] == 0x68 and
             data[p + 3] == 0x65 and data[p + 4] == 0x20) or
                (d0 == 0x2E and data[p + 1] == 0x63 and data[p + 2] == 0x6F and
                 data[p + 3] == 0x6D and data[p + 4] == 0x2F)):
            offset = buckets[hash15(data, p + 5)]
            end = not offset
            while not end:
                wl = w_len[offset]
                transform = w_tr[offset]
                id_ = w_idx[offset]
                offset += 1
                l = wl & 0x1F
                n = n_by_len[l]
                end = (wl & 0x80) != 0
                if transform == 0 and _is_match(l, 0, id_, data, p + 5,
                                                max_length - 5):
                    add(id_ + (41 if d0 == 0x20 else 72) * n, l + 5, l)
                    has_found_match = True
                    if l + 5 < max_length:
                        s = p + l + 5
                        if d0 == 0x20:
                            if (l + 8 < max_length and data[s] == 0x20 and
                                    data[s + 1] == 0x6F and
                                    data[s + 2] == 0x66 and
                                    data[s + 3] == 0x20):
                                add(id_ + 62 * n, l + 9, l)
                                if (l + 12 < max_length and
                                        data[s + 4] == 0x74 and
                                        data[s + 5] == 0x68 and
                                        data[s + 6] == 0x65 and
                                        data[s + 7] == 0x20):
                                    add(id_ + 73 * n, l + 13, l)
    return has_found_match
