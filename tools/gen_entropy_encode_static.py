"""Generates brotli_pure/enc/entropy_encode_static.py from the reference C
header c/enc/entropy_encode_static.h (static Huffman code tables used by
quality 2 / BrotliStoreMetaBlockFast).

Usage: python tools/gen_entropy_encode_static.py /path/to/brotli_reference
"""

import os
import re
import sys

ARRAYS = ['kCodeLengthDepth', 'kStaticCommandCodeDepth',
          'kStaticDistanceCodeDepth', 'kCodeLengthBits', 'kZeroRepsBits',
          'kZeroRepsDepth', 'kNonZeroRepsBits', 'kNonZeroRepsDepth',
          'kStaticCommandCodeBits', 'kStaticDistanceCodeBits']


def parse_array(text, name):
    m = re.search(r'\b' + name + r'\[[^\]]*\]\s*=\s*\{([^}]*)\}', text)
    if not m:
        raise SystemExit('array %s not found' % name)
    return [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', m.group(1))]


def main():
    ref = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(__file__), '..', '..', 'brotli_reference')
    with open(os.path.join(ref, 'c', 'enc', 'entropy_encode_static.h')) as f:
        text = f.read()
    out = os.path.join(os.path.dirname(__file__), '..', 'brotli_pure', 'enc',
                       'entropy_encode_static.py')
    lines = ['"""Static entropy codes (port of c/enc/entropy_encode_static.h).',
             '',
             'GENERATED by tools/gen_entropy_encode_static.py -- do not edit.',
             '"""', '']
    for name in ARRAYS:
        vals = parse_array(text, name)
        lines.append('%s = (' % name)
        for i in range(0, len(vals), 12):
            lines.append('    ' + ', '.join(str(v) for v in vals[i:i + 12]) + ',')
        lines.append(')')
        lines.append('')
    lines += [
        '',
        'def store_static_code_length_code(w):',
        '    """StoreStaticCodeLengthCode."""',
        '    w.write_bits(40, (0x0000FF << 32) | 0x55555554)',
        '',
        '',
        'def store_static_command_huffman_tree(w):',
        '    """StoreStaticCommandHuffmanTree."""',
        '    w.write_bits(56, (0x926244 << 32) | 0x16307003)',
        '    w.write_bits(3, 0x00000000)',
        '',
        '',
        'def store_static_distance_huffman_tree(w):',
        '    """StoreStaticDistanceHuffmanTree."""',
        '    w.write_bits(28, 0x0369DC03)',
        '']
    # Sanity check the constants used above against the header.
    for const in ['0x0000FFu, 0x55555554u', '0x926244U, 0x16307003U',
                  '0x0369DC03u']:
        if const not in text:
            raise SystemExit('constant %s not found in header' % const)
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    main()
