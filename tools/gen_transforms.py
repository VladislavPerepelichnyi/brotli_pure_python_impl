#!/usr/bin/env python3
"""Regenerate tests/rfc_transforms.py from the reference C sources.

Compiles a tiny C program against brotli_reference/c/common/transform.c and
context.c and dumps the 121 RFC 7932 transforms and the literal context
lookup table (RFC 7932 section 7.1) as Python literals, so the test-suite has
an expectation source that is independent of the code under test.

Usage: python tools/gen_transforms.py [path/to/brotli_reference]
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_REF = os.path.normpath(os.path.join(HERE, "..", "..", "..", "brotli_reference"))
OUT = os.path.join(HERE, "..", "tests", "rfc_transforms.py")

C_SRC = r"""
#include <stdio.h>
#include "common/transform.h"
#include "common/context.h"
int main(void) {
  const BrotliTransforms* t = BrotliGetTransforms();
  printf("TRANSFORMS = [\n");
  for (int i = 0; i < (int)t->num_transforms; i++) {
    const uint8_t* p = BROTLI_TRANSFORM_PREFIX(t, i);
    const uint8_t* s = BROTLI_TRANSFORM_SUFFIX(t, i);
    printf("    (b\"");
    for (int k = 1; k <= p[0]; k++) printf("\\x%02x", p[k]);
    printf("\", %d, b\"", BROTLI_TRANSFORM_TYPE(t, i));
    for (int k = 1; k <= s[0]; k++) printf("\\x%02x", s[k]);
    printf("\"),  # %d\n", i);
  }
  printf("]\n\n# CONTEXT_LUT[mode][0][p1] | CONTEXT_LUT[mode][1][p2] = literal context id\n");
  printf("CONTEXT_LUT = [\n");
  for (int m = 0; m < 4; m++) {
    ContextLut lut = BROTLI_CONTEXT_LUT((ContextType)m);
    printf("    (\n");
    for (int h = 0; h < 2; h++) {
      printf("        bytes([");
      for (int k = 0; k < 256; k++) printf("%d%s", lut[h * 256 + k], k < 255 ? "," : "");
      printf("]),\n");
    }
    printf("    ),\n");
  }
  printf("]\n");
  return 0;
}
"""


def main():
    ref = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REF
    cdir = os.path.join(ref, "c")
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "dump.c")
        exe = os.path.join(tmp, "dump")
        with open(src, "w") as f:
            f.write(C_SRC)
        subprocess.check_call(["cc", "-std=c99", "-I", cdir, "-I", os.path.join(cdir, "include"),
                               src, os.path.join(cdir, "common", "transform.c"),
                               os.path.join(cdir, "common", "context.c"), "-o", exe])
        table = subprocess.check_output([exe]).decode()
    with open(OUT, "w") as f:
        f.write('"""RFC 7932 Appendix B transforms: (prefix, type, suffix).\n\n'
                'GENERATED by tools/gen_transforms.py from the reference C sources\n'
                '(c/common/transform.c); do not edit by hand.  Types follow\n'
                'c/common/transform.h: 0 identity, 1..9 omit-last-N, 10 uppercase-first,\n'
                '11 uppercase-all, 12..20 omit-first-(N-11).  CONTEXT_LUT: RFC 7932\n'
                'section 7.1 (modes LSB6, MSB6, UTF8, SIGNED).\n"""\n\n')
        f.write(table)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
